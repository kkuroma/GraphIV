"""
The appendix ablation table, from benchmarks/data/ablation/, which benchmarks/src/graphiv/ablate.py writes

Usage: direnv exec . uv run python paper/scripts/ablation.py
"""

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "benchmarks/data/ablation"
TABLES = Path(__file__).resolve().parents[1] / "tables"
STORED = (20, 50, 100, 200, 250, 500, 1000)
RUNS = [
    ("survey", "surveymatch", "SurveyMatch", (100, 200, 500)),
    ("frontier", "frontiermatch", "FrontierMatch", (20, 50, 100)),
    ("consensus", "consensusmatch", "ConsensusMatch", (20, 50, 100)),
]
LABELS = {
    "full": "tuned recipe",
    "minus_rec": "without \\term{rec}",
    "minus_bm25": "without \\term{bm25}",
    "minus_anc": "without \\term{anc}",
    "minus_fro": "without \\term{fro}",
    "minus_anc2": "without \\term{anc2}",
    "minus_fro2": "without \\term{fro2}",
    "minus_cocite": "without \\term{cocite}",
    "minus_couple": "without \\term{couple}",
    "minus_anc_decay": "without \\term{anc\\_decay}",
    "minus_fro_decay": "without \\term{fro\\_decay}",
    "minus_hub": "without \\term{hub}",
    "anc_only": "\\term{cos} and \\term{anc} only",
    "cos_only_expanded": "\\term{cos} only, expanded pool",
    "no_expansion": "tuned exponents, cosine pool",
    "cosine_pool_order": "cosine, no scorer",
}

rng = np.random.default_rng(0)
body = []
for recipe, dataset, name, ks in RUNS:
    rows = [json.loads(x) for p in sorted(DATA.glob(f"{recipe}-{dataset}_*.jsonl")) for x in p.open()]
    cols = [STORED.index(k) for k in ks]
    mid = cols[1]
    full = np.array([r["recall"]["full"] for r in rows])
    draws = rng.integers(0, len(rows), size=(10_000, len(rows)))
    body.append(f"\\midrule\n\\multicolumn{{5}}{{l}}{{\\emph{{{name}, \\term{{{recipe}}} recipe, {len(rows):,} cases, R@{ks[0]}, R@{ks[1]}, R@{ks[2]}}}}} \\\\")
    for variant, label in LABELS.items():
        if variant not in rows[0]["recall"]:
            continue
        m = np.array([r["recall"][variant] for r in rows])
        diff = (m - full)[:, mid]
        lo, hi = np.percentile(diff[draws].mean(axis=1), [2.5, 97.5])
        change = "" if variant == "full" else f"{diff.mean():+.3f} [{lo:+.3f}, {hi:+.3f}]"
        body.append(f"{label} & " + " & ".join(f"{m.mean(axis=0)[c]:.3f}" for c in cols) + f" & {change} \\\\")
body[0] = body[0].replace("\\midrule\n", "")
caption = "Each tuned recipe on its own benchmark's test split with terms removed. The change is at the middle cutoff, with a 95\\% paired case bootstrap."
head = "variant & R@$k_1$ & R@$k_2$ & R@$k_3$ & change at $k_2$"
(TABLES / "ablation.tex").write_text(
    "% generated by paper/scripts/ablation.py from benchmarks/data/ablation/<recipe>-<benchmark>_<shard>.jsonl\n"
    + f"\\begin{{table*}}[t]\n\\caption{{{caption}}}\n\\label{{tab:ablation}}\n\\centering\n\\small\n\\setlength{{\\tabcolsep}}{{4pt}}\n"
    + f"\\begin{{tabular}}{{lrrrl}}\n\\toprule\n{head} \\\\\n\\midrule\n"
    + "\n".join(body)
    + "\n\\bottomrule\n\\end{tabular}\n\\end{table*}\n"
)
