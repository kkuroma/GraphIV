"""
Table main_recipes: the exponents of BoundedField's four recipes with the benchmark and R@k each was tuned on

Every value is read from the seed-0 tune of one embedder under data/runs/tune
"""

import json
import tomllib
from pathlib import Path

from common import CONFIG, PATHS, output

STEM = Path(__file__).stem
SPEC = CONFIG[STEM]
TUNES = PATHS["RUNS"].parent / "tune"


def tune(recipe: str) -> tuple[dict, dict]:
    """
    One recipe's tuned weights and its report

    Args:
        recipe: focused, survey, frontier or consensus.

    Returns:
        The weights keyed by lowercase term, and the report.json of the tune.
    """
    run = TUNES / f"{SPEC['embedder']}-{recipe}_bf_seed0"
    weights = tomllib.loads((run / "recipe.toml").read_text())["weights"]
    return {k.lower(): v for k, v in weights.items()}, json.loads((run / "report.json").read_text())


def term(name: str) -> str:
    escaped = name.replace("_", "\\_")
    return f"$w_{{\\text{{{escaped}}}}}$"


def main() -> None:
    tunes = {r: tune(r) for r in SPEC["recipes"]}
    lines = [
        f"% generated by benchmarks/scripts/results/{STEM}.py from "
        + ", ".join(f"benchmarks/data/runs/tune/{SPEC['embedder']}-{r}_bf_seed0" for r in SPEC["recipes"]),
        "\\begin{table}[t]",
        "\\caption{The exponents of BoundedField's four recipes, with the benchmark and the R@$k$ each was tuned on.}",
        "\\label{tab:recipes}",
        "\\centering",
        "\\small",
        "\\setlength{\\tabcolsep}{4pt}",
        f"\\begin{{tabular}}{{l{'r' * len(tunes)}}}",
        "\\toprule",
        " & " + " & ".join(f"\\term{{{r}}}" for r in tunes) + " \\\\",
        "\\midrule",
        "\\textbf{Source} & " + " & ".join(SPEC["sources"][rep["spec"]["dataset"]] for _, rep in tunes.values()) + " \\\\",
        "$k$ & " + " & ".join(str(rep["k"]) for _, rep in tunes.values()) + " \\\\",
        "\\midrule",
        *(term(t) + " & " + " & ".join(f"{w.get(t, 0.0):.2f}" for w, _ in tunes.values()) + " \\\\" for t in SPEC["terms"]),
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ]
    output(STEM).with_suffix(".tex").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
